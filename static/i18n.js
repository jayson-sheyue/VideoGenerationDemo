let language = "en";
try {
  const saved = localStorage.getItem("omni-language");
  if (["en", "ja", "zh"].includes(saved)) language = saved;
} catch {}
function t(key) {
  const value = COPY[key];
  return value ? value[{ en: 0, ja: 1, zh: 2 }[language]] || value[0] : key;
}
function translatePage() {
  document.documentElement.lang = { en: "en", ja: "ja", zh: "zh-CN" }[language];
  document
    .querySelectorAll("[data-i18n]")
    .forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document
    .querySelectorAll("[data-i18n-placeholder]")
    .forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
}
